"""Transparent, deterministic chat-reaction scoring for VoxClutch."""
from __future__ import annotations

from collections import deque
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Deque, Iterable

REACTION_WORDS = {
    "pog", "poggers", "letsgo", "let'sgo", "gg", "wow", "bruh", "clutch",
    "insane", "hype", "lol", "lmao", "kekw", "omegalul", "monkas", "hahaha",
}


def parse_time(value: str | datetime) -> datetime:
    if isinstance(value, datetime):
        dt = value
    else:
        dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt.astimezone(timezone.utc)


@dataclass(frozen=True)
class ChatSignal:
    user: str
    text: str
    at: datetime
    event_id: str


class MomentDetector:
    """Emit candidate moments when reaction density crosses an explainable threshold.

    Scoring uses a fixed, auditable weighted index rather than claiming semantic
    understanding. The caller owns persistence and candidate cooldowns.
    """
    def __init__(self, window_seconds: int = 15, min_messages: int = 5,
                 min_unique_chatters: int = 3, threshold: float = 58.0):
        self.window = timedelta(seconds=window_seconds)
        self.min_messages = min_messages
        self.min_unique_chatters = min_unique_chatters
        self.threshold = threshold
        self.events: Deque[ChatSignal] = deque()
        self.seen: set[str] = set()
        self.seen_order: Deque[str] = deque()

    @staticmethod
    def _reaction(text: str) -> bool:
        words = {w.strip("!?.,:;()[]{}<>\"'`).").lower() for w in text.split()}
        return bool(words & REACTION_WORDS) or any(len(w) >= 5 and len(set(w.lower())) <= 2 for w in text.split())

    def ingest(self, user: str, text: str, at: str | datetime, event_id: str) -> dict | None:
        if event_id in self.seen:
            return None
        self.seen.add(event_id)
        self.seen_order.append(event_id)
        if len(self.seen_order) > 4096:
            self.seen.discard(self.seen_order.popleft())
        now = parse_time(at)
        self.events.append(ChatSignal(user=user.strip().lower(), text=text[:500], at=now, event_id=event_id))
        cutoff = now - self.window
        while self.events and self.events[0].at < cutoff:
            self.events.popleft()
        count = len(self.events)
        unique = len({e.user for e in self.events if e.user})
        reaction_count = sum(self._reaction(e.text) for e in self.events)
        if count < self.min_messages or unique < self.min_unique_chatters:
            return None
        # 45% chat velocity, 35% unique participation, 20% recognizable reactions.
        velocity = min(1.0, count / 12.0)
        participation = min(1.0, unique / 8.0)
        reactions = reaction_count / count if count else 0.0
        score = round(100 * (0.45 * velocity + 0.35 * participation + 0.20 * reactions), 1)
        if score < self.threshold:
            return None
        return {
            "score": score,
            "window_start": (now - self.window).isoformat(),
            "window_end": now.isoformat(),
            "signals": {
                "messages": count,
                "unique_chatters": unique,
                "reaction_messages": reaction_count,
                "window_seconds": int(self.window.total_seconds()),
                "score_components": {"chat_velocity": round(velocity, 3), "unique_participation": round(participation, 3), "reaction_density": round(reactions, 3)},
            },
        }

    def reset(self) -> None:
        self.events.clear()
        self.seen.clear()
        self.seen_order.clear()


def score_events(events: Iterable[tuple[str, str, str, str]], **kwargs) -> list[dict]:
    """Test/demo helper returning detections generated by a sequence of events."""
    detector = MomentDetector(**kwargs)
    found = []
    for user, text, at, event_id in events:
        item = detector.ingest(user, text, at, event_id)
        if item:
            found.append(item)
    return found
